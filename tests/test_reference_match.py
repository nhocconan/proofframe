"""Reference-still check for image-to-video clips (stub observer on real ffmpeg media; not a perception benchmark).

Truth boundary under test: no reference -> no check (no fake PASS); a model-reported difference is a review item,
never FAIL; malformed / failed / budget-stopped answers are never PASS; the prompt carries no label or producer claim."""
