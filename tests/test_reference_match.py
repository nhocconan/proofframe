needs_ffmpeg = pytest.mark.skipif(not HAS_FFMPEG, reason="needs ffmpeg")
FORBIDDEN_IN_PROMPT = re.compile(r"muse|meta|grok|seedance|hailuo|kling|veo|sora|wan3|omni|heygen|flux|"
                                 r"ground.truth|seeded|defect|artifact|generated by|prompt was", re.I)


class RefObserver:
    model = "fake-observer"

    def __init__(self, parsed=None, *, ok=True, outcome="ok", error=None):
        self.parsed = {"findings": []} if parsed is None else parsed
        self.ok, self.outcome, self.error = ok, outcome, error
        self.traces, self.calls = [], []

    def observe_images(self, *, images, question, schema, schema_name, purpose):
        self.calls.append({"labels": [lab for lab, _ in images], "question": question, "schema": schema,
                           "schema_name": schema_name, "purpose": purpose,
                           "files": [p for _, p in images]})
        t = {"trace_id": f"tr-{uuid.uuid4().hex[:8]}", "purpose": purpose, "outcome": self.outcome,
             "cost_usd": 0.0, "error": self.error}
        return CallResult(ok=self.ok, parsed=self.parsed if self.ok else None, trace=t, outcome=self.outcome)

    def observe_video(self, **_):
        raise AssertionError("reference-match must not call the video endpoint")


def _clip(path, seconds=3):
    subprocess.run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", f"testsrc2=size=320x180:rate=24:duration={seconds}",
                    "-c:v", "libx264", "-pix_fmt", "yuv420p", str(path)], check=True)
    return path


def _still(path):
    subprocess.run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", "testsrc2=size=640x360:rate=1:duration=1",
                    "-frames:v", "1", str(path)], check=True)
    return path


def _run(tmp_path, observer, *, clip_seconds=3, budget=1.0):
    clip, still = _clip(tmp_path / "c.mp4", clip_seconds), _still(tmp_path / "s.png")
    store = DirStore(tmp_path)
    vsha, rsha = store.put_file(clip, media_type="video/mp4"), store.put_file(still, media_type="image/png")
    contract = build_auto_contract("v", {"sha256": vsha, "duration_ms": clip_seconds * 1000, "has_audio": False},
                                   "t", reference={"asset_id": "v-ref", "sha256": rsha})
    env = run_verification(run_id="r", run_mode="synthetic_fixture", contract_json=contract,
                           assets=[AssetInput("v", 1, vsha, "video"), AssetInput("v-ref", 1, rsha, "image")],
                           store=store, budget=CapBudget(budget), observer=observer,
                           assertion_ids=["reference-match"]).envelope
    return env, env["checks"][0], clip


def _frames(env, check):
    ev = {e["evidence_id"]: e for e in env["evidence"]}
    return [ev[i] for i in check["evidence_ids"] if ev[i]["kind"] == "frame"]


# ---------------------------------------------------------------- contract
def test_reference_adds_hash_bound_slot_and_check():
    probe = {"sha256": "a" * 64, "duration_ms": 5000, "has_audio": False}
    c = Contract.model_validate(build_auto_contract("v", probe, "t", reference={"asset_id": "v-ref",
                                                                              "sha256": "b" * 64}))
    ref = next(a for a in c.assets if a.asset_id == "v-ref")
    assert (ref.role, ref.media_type, ref.canonical_sha256) == ("canonical_reference", "image", "b" * 64)
    chk = next(a for a in c.assertions if a.assertion_id == "reference-match")
    assert chk.reference_asset_ids == ("v-ref",) and chk.target_asset_id == "v" and chk.blocking
    assert chk.observation.kind == "reference_match"
    # different reference -> different contract id (a stored contract is never silently reused)
    other = build_auto_contract("v", probe, "t", reference={"asset_id": "v-ref", "sha256": "c" * 64})
    assert other["contract_id"] != c.contract_id


def test_no_reference_means_no_reference_check():
    c = Contract.model_validate(build_auto_contract(
        "v", {"sha256": "a" * 64, "duration_ms": 5000, "has_audio": False}, "t"))
    assert "reference-match" not in {a.assertion_id for a in c.assertions}
    assert [a.asset_id for a in c.assets] == ["v"]


@pytest.mark.parametrize("ref", [{"asset_id": "v", "sha256": "b" * 64}, {"asset_id": "r", "sha256": "short"}])
def test_bad_reference_is_rejected(ref):
    with pytest.raises(ValueError):
        build_auto_contract("v", {"sha256": "a" * 64, "duration_ms": 5000, "has_audio": False}, "t", reference=ref)


