@needs_ffmpeg
def test_non_png_reference_is_decoded_to_png(tmp_path):
    jpg = tmp_path / "s.jpg"
    subprocess.run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", "testsrc2=size=1920x1080:rate=1:duration=1",
                    "-frames:v", "1", str(jpg)], check=True)
    out = reference.reference_png(jpg, tmp_path / "out" / "REF.png")
    assert out.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"
    small = tmp_path / "small.jpg"
    subprocess.run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", "testsrc2=size=320x180:rate=1:duration=1",
                    "-frames:v", "1", str(small)], check=True)
    probe = media.probe(reference.reference_png(small, tmp_path / "out" / "small.png"))
    assert (probe.width, probe.height) == (320, 180)  # never upscaled


