@needs_ffmpeg
def test_clean_comparison_passes_citing_three_clip_frames(tmp_path):
    obs = RefObserver()
    env, chk, clip = _run(tmp_path, obs)
    assert chk["status"] == "PASS", chk["rationale"]
    frames = _frames(env, chk)
    assert len(frames) >= 3 and all(f["asset_id"] == "v" for f in frames)
    limit = media.clamp_to_video(clip, 10**9)
    starts = sorted(f["start_ms"] for f in frames)
    assert starts[0] == 0 and starts[-1] <= limit and starts[0] < starts[1] < starts[-1]
    assert len(obs.calls) == 1 and obs.calls[0]["labels"] == ["REF", "F1", "F2", "F3"]
    assert obs.calls[0]["schema_name"] == "reference_match"
    assert chk["reference"]["asset_id"] == "v-ref"
    assert env["decision"]["decision"] in ("REVIEW", "ELIGIBLE")  # policy accepted the bindings


@needs_ffmpeg
def test_findings_are_review_items_never_fail(tmp_path):
    obs = RefObserver({"findings": [
        {"category": "new_prop", "severity": "critical", "description": "a lamp on the desk", "frames": ["F2", "F3"]},
        {"category": "missing_prop", "severity": "minor", "description": "no mug", "frames": ["F1"]},
        {"category": "scene_changed", "severity": "major", "description": "window moved", "frames": ["F1", "F1"]}]})
    env, chk, _ = _run(tmp_path, obs)
    assert chk["status"] == "UNCERTAIN" and env["decision"]["decision"] == "REVIEW"
    assert [f["category"] for f in chk["findings"]] == ["new_prop", "missing_prop", "scene_changed"]
    assert [f["severity"] for f in chk["findings"]] == ["critical", "minor", "major"]
    assert all(f["verdict"] == "review" for f in chk["findings"])
    ev = {e["evidence_id"]: e for e in env["evidence"]}
    for f in chk["findings"]:
        assert f["evidence_ids"] and all(ev[i]["kind"] == "frame" and ev[i]["asset_id"] == "v"
                                         for i in f["evidence_ids"])
    assert len(chk["findings"][2]["evidence_ids"]) == 1  # duplicate frame label collapsed
    assert not any(r["status"] == "FAIL" for r in env["report"]["results"])


@needs_ffmpeg
def test_prompt_has_no_label_model_name_or_producer_claim(tmp_path):
    obs = RefObserver()
    env, chk, _ = _run(tmp_path, obs)
    call = obs.calls[0]
    payload = call["question"] + json.dumps(call["schema"])
    assert not FORBIDDEN_IN_PROMPT.search(payload), FORBIDDEN_IN_PROMPT.search(payload)
    contract = Contract.model_validate(build_auto_contract(
        "v", {"sha256": "a" * 64, "duration_ms": 3000, "has_audio": False}, "t",
        reference={"asset_id": "v-ref", "sha256": "b" * 64}))
    spec = next(a for a in contract.assertions if a.assertion_id == "reference-match")
    assert spec.expected not in payload and spec.predicate not in payload
    assert chk["observation_question"] == call["question"]


