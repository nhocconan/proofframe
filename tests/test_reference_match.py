# ---------------------------------------------------------------- CLI
def _cli_transport(seen):
    def transport(request):
        if request.url.path == "/v1/assets":
            body = request.content
            is_image = b'name="media_type"\r\n\r\nimage' in body
            seen["uploads"].append("image" if is_image else "video")
            return httpx.Response(201, json={"asset_id": "x", "revision": 1,
                                             "sha256": ("b" if is_image else "a") * 64})
        seen["body"] = json.loads(request.content)
        return httpx.Response(202, json={"run_id": "run-1"})
    return transport


def test_cli_uploads_reference_as_image_and_submits_both_assets(tmp_path, monkeypatch):
    video, still = tmp_path / "clip.mp4", tmp_path / "still.png"
    video.write_bytes(b"video-fixture")
    still.write_bytes(b"png-fixture")
    seen = {"uploads": []}
    monkeypatch.setattr(cli, "_c", lambda: httpx.Client(base_url="https://test",
                                                        transport=httpx.MockTransport(_cli_transport(seen))))
    cli.main(["verify", "--video-only", "--video", f"clip={video}", "--reference", str(still)])
    assert seen["uploads"] == ["video", "image"]
    assert seen["body"] == {"mode": "video_only", "run_mode": "live", "assets": [
        {"asset_id": "clip", "sha256": "a" * 64}, {"asset_id": "clip-reference", "sha256": "b" * 64}]}


